bool is_close(float a, float b)
{
    if (std::isnan(a))
    {
        return std::isnan(b);
    }
    if (std::isinf(a))
    {
        return a == b;
    }
    return std::abs(a - b) <= 20 * std::numeric_limits<float>::epsilon();

}

